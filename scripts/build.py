#!/usr/bin/env python3
"""Build dist/ for the Paradise Lost reading guide.

Merges data/text.json (the 1674 text, public domain), data/guide/book-NN.json (notes),
data/characters.json and data/listen.json into dist/data.js, and copies src/.
"""
import json, os, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
DIST = os.path.join(ROOT, "dist")


def load(*parts):
    with open(os.path.join(DATA, *parts), encoding="utf-8") as f:
        return json.load(f)


def main():
    books = load("text.json")
    assert len(books) == 12, len(books)
    chars = load("characters.json")
    ids = {c["id"] for c in chars}
    guide = {}
    for b in books:
        p = os.path.join(DATA, "guide", f"book-{b['n']:02d}.json")
        if not os.path.exists(p):
            print(f"warning: no guide for book {b['n']}", file=sys.stderr)
            continue
        g = load("guide", f"book-{b['n']:02d}.json")
        # Who is in a book comes from the character list, so the two never disagree.
        g["characters"] = [c["id"] for c in chars if b["n"] in c["books"]]
        guide[b["n"]] = g
    for c in chars:
        for k in ("first", "quote"):
            assert 1 <= c[k]["book"] <= 12, (c["id"], k)
    listen = load("listen.json")
    # Doré's 1866 plates (public domain): art/plates.json maps each plate to a book and line.
    plates = []
    pj = os.path.join(ROOT, "art", "plates.json")
    if os.path.exists(pj):
        with open(pj, encoding="utf-8") as f:
            plates = sorted(json.load(f), key=lambda x: x["plate"])
        for pl in plates:
            assert os.path.exists(os.path.join(ROOT, "art", "web", f"{pl['plate']:02d}.jpg")), pl
            assert 1 <= pl["line"] <= len(books[pl["book"] - 1]["lines"]), pl
    if os.path.isdir(DIST):
        shutil.rmtree(DIST)
    shutil.copytree(os.path.join(ROOT, "src"), DIST)
    if plates:
        shutil.copytree(os.path.join(ROOT, "art", "web"), os.path.join(DIST, "art"))
    # Read-along timings (scripts/align.py). The audio itself is streamed from archive.org, never stored here.
    adir = os.path.join(DATA, "audio")
    if os.path.isdir(adir):
        os.makedirs(os.path.join(DIST, "audio"), exist_ok=True)
        for fn in sorted(os.listdir(adir)):
            if fn.endswith(".json"):
                shutil.copy(os.path.join(adir, fn), os.path.join(DIST, "audio", fn))
    data = {"books": books, "guide": guide, "characters": chars, "listen": listen, "plates": plates}
    with open(os.path.join(DIST, "data.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/build.py. Do not edit.\n")
        f.write("window.PL = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    lines = sum(len(b["lines"]) for b in books)
    print(f"built dist/ · 12 books · {lines} lines · {len(guide)} guides · {len(ids)} characters · {len(plates)} plates · {len(os.listdir(os.path.join(DIST, 'audio'))) if os.path.isdir(os.path.join(DIST, 'audio')) else 0} read-alongs · "
          f"{os.path.getsize(os.path.join(DIST, 'data.js')) // 1024} KB data")


if __name__ == "__main__":
    sys.exit(main())
